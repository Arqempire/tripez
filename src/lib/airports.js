export function searchMasterAirports(query) {
  if (!query) return MASTER_AIRPORTS.slice(0, 10);
  const q = query.trim().toLowerCase();
  
  // Exact code match priority
  const exactCodeMatch = MASTER_AIRPORTS.filter(ap => ap.code.toLowerCase() === q);
  if (exactCodeMatch.length > 0) {
    const rest = MASTER_AIRPORTS.filter(ap => ap.code.toLowerCase() !== q && (
      ap.code.toLowerCase().includes(q) ||
      ap.city.toLowerCase().includes(q) ||
      ap.country.toLowerCase().includes(q) ||
      ap.name.toLowerCase().includes(q)
    ));
    return [...exactCodeMatch, ...rest].slice(0, 12);
  }

  return MASTER_AIRPORTS.filter(
    ap =>
      ap.code.toLowerCase().includes(q) ||
      ap.city.toLowerCase().includes(q) ||
      ap.country.toLowerCase().includes(q) ||
      ap.name.toLowerCase().includes(q)
  ).slice(0, 12);
}

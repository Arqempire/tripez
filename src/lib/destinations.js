/**
 * Smart Destination Normalizer
 * Example: "Plan a 5-day trip to Kashmir" -> "kashmir"
 * Example: "Gulmarg, Jammu & Kashmir, India" -> "kashmir"
 */
export function normalizeDestination(rawInput) {
  if (!rawInput || typeof rawInput !== "string") return "";

  // 1. Clean prompt filler phrases
  let cleaned = rawInput
    .toLowerCase()
    .replace(/^(plan|create|build|show|generate)\s+a\s+(\d+-day\s+)?(trip|itinerary|vacation|tour)\s+(to|for|in)\s+/i, "")
    .replace(/^(trip\s+to|vacation\s+in|tour\s+of)\s+/i, "")
    .trim();

  // 2. Extract primary comma parts (e.g. "Gulmarg, Jammu & Kashmir, India")
  const parts = cleaned.split(",").map(s => s.trim()).filter(Boolean);

  // Check direct alias matching on parts or full cleaned text
  for (const part of parts) {
    if (DESTINATION_ALIASES[part]) {
      return DESTINATION_ALIASES[part];
    }
  }

  if (DESTINATION_ALIASES[cleaned]) {
    return DESTINATION_ALIASES[cleaned];
  }

  // 3. Partial alias matching
  for (const [alias, targetKey] of Object.entries(DESTINATION_ALIASES)) {
    if (cleaned.includes(alias)) {
      return targetKey;
    }
  }

  // 4. Return clean destination (primary place + country if available)
  if (parts.length >= 2) {
    const primary = parts[0];
    const country = parts[parts.length - 1];
    return `${primary} ${country}`.trim();
  }

  return parts[0] || cleaned;
}
